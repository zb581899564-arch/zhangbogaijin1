def analyze(seed):
    events=SOURCE/str(seed)/'NATIVE/pipeline.jsonl';library=FactoryLibrary();inherited=None;transitions=[];cycle_inputs={}
    with events.open(encoding='utf-8') as stream:
        for line in stream:
            e=json.loads(line)
            if e['kind']=='selection':inherited=[duty(i%100) for i in e['selected']]
            elif e['kind']=='population':
                phase=e['phase'];points=e['points'];cycle=e['cycle']
                if phase=='INITIAL':
                    for p in points:library.add(p,'UNKNOWN_INITIAL')
                elif phase=='PRE_GLOBAL':
                    assigned=regroup(points)
                    if inherited is not None:transitions.append(dict(cycle=cycle,**switch_summary(points,inherited,assigned)))
                    cycle_inputs[cycle]={}
                    for p,r in zip(points,assigned):cycle_inputs[cycle].setdefault(p['lineage'],set()).add(r)
                elif phase in ('POST_GLOBAL','POST_LOCAL'):
                    for i,p in enumerate(points):
                        role=duty(i)
                        if phase=='POST_GLOBAL':assert role in cycle_inputs[cycle][p['lineage']]
                        library.add(p,role)
                    if phase=='POST_GLOBAL':
                        for p in points[15:70]:library.query(p,cycle,e['fe'])
    assert len(library.requests)==550 and len(transitions)==10
    # Cycle11pre is recorded but no complete generation follows: disclose it, use1..10only.
    complete=[r for r in transitions if r['cycle']<=10];assert len(complete)==9
    return dict(seed=seed,roleTransitions=complete,partialCycle11Transition=transitions[-1],factoryLibrary=library.summary(),
                factoryQueries=library.requests,extraSearchFE=0,extraDecoderCalls=0)


